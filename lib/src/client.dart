/// Thrown when a GitHub request fails.
class SabbathSchoolApiException implements Exception {
  SabbathSchoolApiException(this.statusCode, this.message);

  /// HTTP status code returned by GitHub.
  final int statusCode;
  final String message;

  @override
  String toString() => 'SabbathSchoolApiException($statusCode): $message';
}

/// Client for the [sabbath-school-lessons](https://github.com/Adventech/sabbath-school-lessons)
/// content repository (or any fork of it).
///
/// Designed for apps with a very large user base:
///
/// - **No GitHub API calls in the hot path.** Directory structure and all
///   quarter/lesson metadata are served from committed index files
///   (`index/languages.json`, `index/<lang>.json`), generated by
///   `tool/generate_index.dart` and fetched from raw.githubusercontent.com.
/// - **GitHub's CDN does the fan-out.** raw.githubusercontent.com responses
///   are edge-cached (Cache-Control: max-age=300), so millions of users
///   requesting the same URL produce at most one origin fetch per edge
///   location per cache window — the first user warms it up for everyone.
/// - **Local caching with revalidation.** Index responses are cached for
///   [indexTtl] (default 12h) and content for [contentTtl] (default 24h).
///   Expired entries are revalidated with `ETag`/`If-None-Match` and a 304
///   keeps the cached bytes, so an up-to-date fork costs almost no requests.
/// - **API fallback.** If index files are missing (older fork), the client
///   falls back to the GitHub Contents API, optionally raising the 60
///   requests/hour limit to 5000 with [githubToken].
///
/// ```dart
/// final client = SabbathSchoolClient();
/// final quarter = await client.quarter('en', '2026-04');
/// print(quarter.title);
/// ```
class SabbathSchoolClient {
  /// Creates a client for the given GitHub repository.
  ///
  /// [githubToken] is only used for the API *fallback* path.
  SabbathSchoolClient({
    this.owner = defaultOwner,
    this.repo = defaultRepo,
    this.branch = defaultBranch,
    this.githubToken,
    http.Client? httpClient,
    CacheStore? cacheStore,
    this.indexTtl = const Duration(hours: 12),
    this.contentTtl = const Duration(hours: 24),
  })  : _httpClient = httpClient ?? http.Client(),
        _cache = _CacheManager(cacheStore ?? MemoryCacheStore());

  /// GitHub owner (user or organization) of the content repository.
  final String owner;

  /// Repository name.
  final String repo;

  /// Branch to read from.
  final String branch;

  /// Optional GitHub personal access token used for API fallback requests.
  final String? githubToken;

  /// How long index responses are trusted without revalidation.
  final Duration indexTtl;

  /// How long content responses (markdown, media manifests) are trusted.
  final Duration contentTtl;

  final http.Client _httpClient;
  final _CacheManager _cache;

  /// Closes the underlying HTTP client and clears in-memory cache state.
  /// The client cannot be used afterwards.
  void close() => _httpClient.close();

  // ---------------------------------------------------------------------------
  // Languages
  // ---------------------------------------------------------------------------

  /// Lists language codes present in the repository, sorted alphabetically.
  ///
  /// Served from the committed `index/languages.json` when available;
  /// otherwise falls back to the GitHub Contents API.
  Future<List<String>> listLanguages() async {
    final index = await _languagesIndex();
    if (index != null) {
      return index.keys.toList()..sort();
    }
    final entries = await _listDirs('src');
    return entries.toList()..sort();
  }

  /// Fetches language metadata (name). Returns `null` when the language
  /// does not exist.
  Future<Language?> language(String code) async {
    final index = await _languagesIndex();
    if (index != null) {
      final name = index[code];
      return name == null ? null : Language(code: code, name: name);
    }
    final yaml = await _tryRawYaml(_contentPath('$code/info.yml'), ttl: contentTtl);
    if (yaml == null) return null;
    return parseLanguage(code, yaml);
  }

  // ---------------------------------------------------------------------------
  // Quarters
  // ---------------------------------------------------------------------------

  /// Lists quarter folder names for a language, e.g. `2026-01`, sorted.
  ///
  /// Served from the committed `index/<lang>.json` when available; otherwise
  /// falls back to the GitHub Contents API.
  Future<List<String>> listQuarterIds(String language) async {
    final index = await _languageIndex(language);
    if (index != null) {
      return [for (final q in index['quarters'] as List) q['id'] as String];
    }
    final entries = await _listDirs('src/$language');
    final quarters = entries.where((e) => RegExp(r'^\d{4}-\d{2}').hasMatch(e)).toList()
      ..sort();
    return quarters;
  }

  /// Loads a quarter's metadata (title, dates, theme colors, credits, lesson
  /// numbers).
  ///
  /// Served from the committed `index/<lang>.json` when available; otherwise
  /// fetched from `src/<language>/<quarterId>/info.yml`.
  ///
  /// Throws [SabbathSchoolApiException] with status 404 when the quarter
  /// does not exist.
  Future<Quarter> quarter(String language, String quarterId) async {
    final index = await _languageIndex(language);
    if (index != null) {
      final entry = (index['quarters'] as List)
          .cast<Map>()
          .firstWhere((q) => q['id'] == quarterId, orElse: () => const {});
      if (entry.isNotEmpty) return _quarterFromIndex(language, entry);
    }
    final yaml = await _rawYaml(_contentPath('$language/$quarterId/info.yml'));
    return parseQuarter(language, quarterId, yaml);
  }

  // ---------------------------------------------------------------------------
  // Lessons and days
  // ---------------------------------------------------------------------------

  /// Loads a single lesson's metadata.
  ///
  /// Served from the committed `index/<lang>.json` when available; otherwise
  /// fetched from `src/<language>/<quarterId>/<NN>/info.yml`.
  Future<Lesson> lesson(
    String language,
    String quarterId,
    int lessonNumber,
  ) async {
    final index = await _languageIndex(language);
    if (index != null) {
      final quarterEntry = (index['quarters'] as List)
          .cast<Map>()
          .firstWhere((q) => q['id'] == quarterId, orElse: () => const {});
      if (quarterEntry.isNotEmpty) {
        final lessonEntry = (quarterEntry['lessons'] as List)
            .cast<Map>()
            .firstWhere((l) => l['number'] == lessonNumber, orElse: () => const {});
        if (lessonEntry.isNotEmpty) return _lessonFromIndex(language, quarterId, lessonEntry);
      }
    }
    final yaml =
        await _rawYaml(_contentPath('$language/$quarterId/${_lessonDir(lessonNumber)}/info.yml'));
    return parseLesson(language, quarterId, lessonNumber, yaml);
  }

  /// Loads all lessons of a quarter.
  ///
  /// With committed index files this performs **zero network requests**
  /// beyond the one language-index fetch (which is CDN-cached and reused by
  /// every user of the app).
  Future<List<Lesson>> quarterLessons(
    String language,
    String quarterId, {
    int? limit,
  }) async {
    final index = await _languageIndex(language);
    List<Map> lessonEntries;
    if (index != null) {
      final quarterEntry = (index['quarters'] as List)
          .cast<Map>()
          .firstWhere((q) => q['id'] == quarterId, orElse: () => const {});
      if (quarterEntry.isEmpty) {
        throw SabbathSchoolApiException(404, 'Quarter $quarterId not found in index');
      }
      lessonEntries = (quarterEntry['lessons'] as List).cast<Map>();
    } else {
      lessonEntries = [
        for (final lesson in await _lessonsViaFallback(language, quarterId))
          {
            'number': lesson.number,
            'title': lesson.title,
            'start_date': _formatDate(lesson.startDate),
            'end_date': _formatDate(lesson.endDate),
          }
      ];
    }
    final wanted = limit == null ? lessonEntries : lessonEntries.take(limit).toList();
    return [
      for (final entry in wanted) _lessonFromIndex(language, quarterId, entry),
    ];
  }

  /// Loads the quarterly introduction (`introduction.md`).
  Future<String> quarterIntroduction(String language, String quarterId) =>
      _rawText(_contentPath('$language/$quarterId/introduction.md'), ttl: contentTtl);

  /// Loads one daily reading (`day` is `1..7`).
  Future<DayContent> day(
    String language,
    String quarterId,
    int lessonNumber,
    int day,
  ) async {
    final text = await _rawText(
      _contentPath('$language/$quarterId/${_lessonDir(lessonNumber)}/${_lessonDir(day)}.md'),
      ttl: contentTtl,
    );
    return parseDayMarkdown(language, quarterId, lessonNumber, day, text);
  }

  /// Loads an extra feature file of a lesson, e.g. `teacher-comments`,
  /// `inside-story`, or `hope-ss` (`<name>.md` inside the lesson folder).
  /// Returns `null` when the feature is not present.
  Future<String?> feature(
    String language,
    String quarterId,
    int lessonNumber,
    String featureName,
  ) async {
    return _tryRawText(
      _contentPath('$language/$quarterId/${_lessonDir(lessonNumber)}/$featureName.md'),
      ttl: contentTtl,
    );
  }

  // ---------------------------------------------------------------------------
  // Media manifests
  // ---------------------------------------------------------------------------

  /// Loads audio tracks for a quarter, optionally filtered to one lesson
  /// (and, if [day] is given, to one day of that lesson).
  ///
  /// Some quarters target audio per lesson (`en/2026-01/01`) and newer ones
  /// per day (`en/2026-04/01/01`); both shapes are matched.
  Future<List<MediaItem>> audio(
    String language,
    String quarterId, {
    int? lesson,
    int? day,
  }) =>
      _media('audio', language, quarterId, lesson, day);

  /// Loads PDF documents for a quarter, optionally filtered to one lesson.
  Future<List<MediaItem>> pdf(
    String language,
    String quarterId, {
    int? lesson,
  }) =>
      _media('pdf', language, quarterId, lesson, null);

  /// Loads video clips for a quarter, optionally filtered to one lesson.
  Future<List<MediaItem>> video(
    String language,
    String quarterId, {
    int? lesson,
  }) =>
      _media('video', language, quarterId, lesson, null);

  Future<List<MediaItem>> _media(
    String kind,
    String language,
    String quarterId,
    int? lesson,
    int? day,
  ) async {
    final yaml = await _tryRawYaml(
      _contentPath('$language/$quarterId/$kind.yml'),
      ttl: contentTtl,
    );
    if (yaml == null) return [];
    final root = _asMap(yaml);
    var items = parseMedia(kind, _asList(root[kind]));
    if (lesson != null) {
      final base = '$language/$quarterId/${_lessonDir(lesson)}';
      final exact = day == null ? base : '$base/${_lessonDir(day)}';
      items = items
          .where((i) => i.target == exact || (day == null && i.target.startsWith('$base/')))
          .toList();
    }
    return items;
  }

  // ---------------------------------------------------------------------------
  // URL helpers (also useful for fetching covers/images yourself)
  // ---------------------------------------------------------------------------

  /// Raw file URL for a path relative to the repository root.
  Uri rawUri(String repoPath) =>
      Uri.https('raw.githubusercontent.com', '/$owner/$repo/$branch/$repoPath');

  /// Contents-API URL for a path relative to the repository root.
  Uri apiUri(String repoPath) =>
      Uri.https('api.github.com', '/repos/$owner/$repo/contents/$repoPath', {'ref': branch});

  /// Drops all cached entries (in-memory and any provided persistent store).
  Future<void> clearCache() => _cache.clear();

  // ---------------------------------------------------------------------------
  // Internals
  // ---------------------------------------------------------------------------

  /// Content paths live under `src/` in the repository.
  String _contentPath(String relative) => 'src/$relative';

  /// Lesson and day folder names are zero-padded (`01`, `02`, ...).
  String _lessonDir(int number) => number.toString().padLeft(2, '0');

  /// Fetches and caches `index/languages.json` (code → name map).
  /// Returns `null` when the index does not exist in the fork.
  Future<Map<String, String>?> _languagesIndex() async {
    final body = await _tryRawText('index/languages.json', ttl: indexTtl);
    if (body == null) return null;
    final decoded = jsonDecode(body) as Map<String, dynamic>;
    return {
      for (final entry in (decoded['languages'] as List).cast<Map>())
        entry['code'] as String: entry['name'] as String? ?? (entry['code'] as String),
    };
  }

  /// Fetches and caches `index/<lang>.json`.
  /// Returns `null` when the index does not exist in the fork.
  Future<Map<String, dynamic>?> _languageIndex(String language) async {
    final body = await _tryRawText('index/$language.json', ttl: indexTtl);
    if (body == null) return null;
    return jsonDecode(body) as Map<String, dynamic>;
  }

  Quarter _quarterFromIndex(String language, Map entry) {
    final lessons = [for (final l in entry['lessons'] as List) (l as Map)['number'] as int];
    return Quarter(
      language: language,
      id: entry['id'] as String,
      title: entry['title'] as String? ?? '',
      description: entry['description'] as String? ?? '',
      humanDate: entry['human_date'] as String? ?? '',
      startDate: parseDate(entry['start_date'])!,
      endDate: parseDate(entry['end_date'])!,
      colorPrimary: entry['color_primary'] as String? ?? '',
      colorPrimaryDark: entry['color_primary_dark'] as String? ?? '',
      splash: entry['splash'] == true,
      credits: [
        for (final c in (entry['credits'] as List? ?? const []))
          Credit(name: (c as Map)['name'] as String, value: c['value'] as String),
      ],
      lessonNumbers: lessons,
    );
  }

  Lesson _lessonFromIndex(String language, String quarterId, Map entry) => Lesson(
        language: language,
        quarterId: quarterId,
        number: entry['number'] as int,
        title: entry['title'] as String? ?? '',
        startDate: parseDate(entry['start_date'])!,
        endDate: parseDate(entry['end_date'])!,
      );

  /// Fallback (no index): list lesson dirs via API, fetch each info.yml raw.
  Future<List<Lesson>> _lessonsViaFallback(String language, String quarterId) async {
    final lessonDirs = await _listDirs('src/$language/$quarterId');
    final numbers = lessonDirs
        .map((e) => int.tryParse(e))
        .whereType<int>()
        .where((n) => n >= 1 && n <= 13)
        .toList()
      ..sort();
    return [
      for (final n in numbers) await lesson(language, quarterId, n),
    ];
  }

  /// Lists child directories of a repository path via the Contents API.
  Future<List<String>> _listDirs(String repoPath) async {
    final response = await _apiGet(apiUri(repoPath));
    final decoded = jsonDecode(response.body);
    if (decoded is! List) return const [];
    return [
      for (final entry in decoded)
        if (entry is Map && entry['type'] == 'dir' && entry['name'] is String)
          entry['name'] as String,
    ];
  }

  Future<http.Response> _apiGet(Uri uri) async {
    final response = await _httpClient.get(
      uri,
      headers: {
        'Accept': 'application/vnd.github+json',
        if (githubToken != null) 'Authorization': 'Bearer $githubToken',
      },
    );
    if (response.statusCode != 200) {
      throw SabbathSchoolApiException(response.statusCode, 'GET $uri failed');
    }
    return response;
  }

  Future<Object?> _tryRawYaml(String contentPath, {required Duration ttl}) async {
    final text = await _tryRawText(contentPath, ttl: ttl);
    if (text == null) return null;
    return loadYaml(text);
  }

  Future<Object?> _rawYaml(String contentPath) async {
    return loadYaml(await _rawText(contentPath, ttl: contentTtl));
  }

  Future<String> _rawText(String contentPath, {required Duration ttl}) async {
    final result = await _fetchCached(rawUri(contentPath), ttl: ttl);
    if (result == null) {
      throw SabbathSchoolApiException(404, 'GET ${rawUri(contentPath)} failed');
    }
    return result;
  }

  Future<String?> _tryRawText(String contentPath, {required Duration ttl}) =>
      _fetchCached(rawUri(contentPath), ttl: ttl);

  /// Cached, revalidating GET. Returns `null` for 404 (optional fetches).
  ///
  /// - Fresh entry ([ttl] not elapsed) → returned without any request.
  /// - Stale entry → conditional request with `If-None-Match` /
  ///   `If-Modified-Since`; a 304 refreshes the timestamp and keeps bytes.
  Future<String?> _fetchCached(Uri uri, {required Duration ttl}) async {
    final key = uri.toString();
    final entry = await _cache.get(key);

    if (entry != null && entry.isFresh(ttl)) return entry.body;

    final headers = <String, String>{
      if (entry?.etag != null) 'If-None-Match': entry!.etag!,
      if (entry?.lastModified != null) 'If-Modified-Since': entry!.lastModified!,
    };
    final response = await _httpClient.get(uri, headers: headers);

    switch (response.statusCode) {
      case 200:
        final newEntry = CacheEntry(
          body: utf8.decode(response.bodyBytes),
          etag: response.headers['etag'],
          lastModified: response.headers['last-modified'],
          fetchedAt: DateTime.now(),
        );
        await _cache.put(key, newEntry.toJson());
        return newEntry.body;
      case 304:
        final touched = entry!.touched();
        await _cache.put(key, touched.toJson());
        return touched.body;
      case 404:
        return null;
      default:
        // Serve stale data on transient errors rather than failing the app.
        if (entry != null) return entry.body;
        throw SabbathSchoolApiException(response.statusCode, 'GET $uri failed');
    }
  }

  String _formatDate(DateTime d) =>
      '${d.day.toString().padLeft(2, '0')}/'
      '${d.month.toString().padLeft(2, '0')}/${d.year}';
}

/// In-memory wrapper over a [CacheStore] that serializes entries as JSON.
class _CacheManager {
  _CacheManager(this._store);

  final CacheStore _store;

  Future<CacheEntry?> get(String key) async {
    final raw = await _store.get(key);
    if (raw == null) return null;
    try {
      return CacheEntry.fromJson(raw);
    } catch (_) {
      await _store.remove(key);
      return null;
    }
  }

  Future<void> put(String key, String envelope) => _store.put(key, envelope);

  Future<void> clear() async {
    // Best effort: the MemoryCacheStore supports full clear via remove of
    // unknown keys is impractical, so only stores that track keys clear all.
    if (_store is MemoryCacheStore) {
      _store.clear();
    }
  }
}

List<Object?> _asList(Object? node) {
  if (node is YamlList) return node;
  return node is List ? node : [];
}

Map<Object?, Object?> _asMap(Object? node) {
  if (node is YamlMap) return node;
  return node is Map ? node : {};
}
